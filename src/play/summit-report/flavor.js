// 최근 사건을 말하는 묶음(늦게 시작하는 묶음)을 조금 더 자주 고른다.
function flavorPick(pool) {
  S.flavorUsed = S.flavorUsed || {};
  const used = (S.flavorUsed[pool] = S.flavorUsed[pool] || new Set());
  const open = FLAVOR[pool].filter((g) => S.t >= toMin(g.from) && S.t < toMin(g.to) && (!g.when || g.when()) && (!g.seg || g.seg === S.seg));
  let cand = [];
  for (const g of open) for (const s of g.lines) if (!used.has(s)) for (let i = 0; i < (g.when ? 3 : toMin(g.from) >= S.t - 60 ? 2 : 1); i++) cand.push(s);
  if (!cand.length) { for (const g of open) for (const s of g.lines) used.delete(s); cand = open.flatMap((g) => g.lines); }
  if (!cand.length) return null;
  const s = pick(cand);
  used.add(s);
  return s;
}
